// scripts/download-character-wiki-art.cjs
//
// Downloads every character's official card art (resolved by
// generate-character-wiki-art.cjs + confirmed by verify-character-wiki-art.cjs
// against the wiki's own canonical page image) into this repo, following the
// EXACT same convention every other piece of game art already uses (see
// adapters/game-definitions/<game>/icons/README.md): drop a file under
// icons/<category>/<id>.<ext>, served automatically via the existing
// fm-icon:// protocol (Electron) / jsDelivr CDN (web) — no new serving
// mechanism, no runtime network fetch to a third party at all afterward.
//
// Run AFTER generate-character-wiki-art.cjs (reads its output).
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');

function parseWikiArt() {
    const src = fs.readFileSync(path.join(ROOT, 'shared/game-data/character-wiki-art.ts'), 'utf8');
    const entries = [];
    const re = /'([\w-]+)':\s*\{\s*host:\s*'([^']+)',\s*fileTitle:\s*'((?:[^'\\]|\\.)*)'/g;
    let m;
    while ((m = re.exec(src))) entries.push({ id: m[1], host: m[2], fileTitle: m[3].replace(/\\'/g, "'") });
    return entries;
}

async function resolveUrl(host, fileTitle) {
    const url = `https://${host}/api.php?action=query&titles=${encodeURIComponent('File:' + fileTitle)}&prop=imageinfo&iiprop=url&format=json`;
    const res = await fetch(url, { signal: AbortSignal.timeout(15000) });
    if (!res.ok) return null;
    const json = await res.json();
    const page = Object.values(json?.query?.pages ?? {})[0];
    return page?.imageinfo?.[0]?.url ?? null;
}

async function download(url, destPath) {
    const res = await fetch(url, { signal: AbortSignal.timeout(30000) });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const buf = Buffer.from(await res.arrayBuffer());
    fs.writeFileSync(destPath, buf);
    return buf.length;
}

async function main() {
    const entries = parseWikiArt();
    const gameOf = (host) => (host.includes('genshin') ? 'genshin-impact' : 'wuthering-waves');
    const bundled = {};
    let totalBytes = 0;
    const failures = [];

    for (const entry of entries) {
        const gameId = gameOf(entry.host);
        const ext = path.extname(entry.fileTitle).toLowerCase() || '.png';
        const destDir = path.join(ROOT, 'adapters/game-definitions', gameId, 'icons/characters-card');
        fs.mkdirSync(destDir, { recursive: true });
        const destPath = path.join(destDir, `${entry.id}${ext}`);
        try {
            const realUrl = await resolveUrl(entry.host, entry.fileTitle);
            if (!realUrl) throw new Error('no imageinfo url resolved');
            const bytes = await download(realUrl, destPath);
            totalBytes += bytes;
            bundled[entry.id] = `icons/characters-card/${entry.id}${ext}`;
            console.log(`OK  ${gameId}/${entry.id}  ${(bytes / 1024).toFixed(0)}KB`);
        } catch (e) {
            failures.push(`${gameId}/${entry.id}: ${e.message}`);
            console.log(`FAIL ${gameId}/${entry.id}: ${e.message}`);
        }
    }

    console.log(`\nDownloaded ${Object.keys(bundled).length}/${entries.length} — total ${(totalBytes / 1024 / 1024).toFixed(1)}MB`);
    if (failures.length > 0) {
        console.log(`\n${failures.length} FAILURES:`);
        failures.forEach((f) => console.log('  ' + f));
    }

    const body = Object.entries(bundled).map(([id, p]) => `    '${id}': '${p}',`).join('\n');
    fs.writeFileSync(
        path.join(ROOT, 'shared/game-data/character-card-art.ts'),
        `/** Generated by scripts/download-character-wiki-art.cjs — id -> bundled icon path,\n` +
        ` * served the SAME way every other piece of game art already is (fm-icon:// in\n` +
        ` * Electron, jsDelivr CDN on the web build — see iconSrc() in lib/icons.ts). No\n` +
        ` * runtime network fetch to a third party; see character-wiki-art.ts for where\n` +
        ` * each file was originally sourced from (kept as a provenance record). */\n` +
        `export const CHARACTER_CARD_ART: Record<string, string> = {\n${body}\n};\n`,
    );
    console.log('\nWrote shared/game-data/character-card-art.ts (id -> bundled relative path)');
}

main().catch((e) => { console.error(e); process.exit(1); });
